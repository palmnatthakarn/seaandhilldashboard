const fs = require('fs');
const path = require('path');
const {
  createClickHouse,
  getColumns,
  getCreateTable,
  queryRows,
  readConfig,
} = require('./cdc-clickhouse-utils');

const OUTPUT_PATH = path.resolve('docs', 'cdc-clickhouse-schema-dump.sql');

async function main() {
  const { data: config } = readConfig(process.argv[2]);
  const ch = createClickHouse(config);

  try {
    const objects = await queryRows(ch, `
      SELECT name, engine
      FROM system.tables
      WHERE database = currentDatabase()
        AND (
          name LIKE '%_queue'
          OR name LIKE '%_mv'
          OR name LIKE '%_raw'
          OR name IN (
            'purchase_transaction',
            'purchase_transaction_detail',
            'saleinvoice_transaction',
            'saleinvoice_transaction_detail',
            'stock_transaction',
            'payment_transaction',
            'journal_transaction_detail'
          )
        )
      ORDER BY name
    `);

    const chunks = [];
    chunks.push(`-- Generated by scripts/dump-cdc-clickhouse-schema.js`);
    chunks.push(`-- Database: ${config.clickhouse.database}`);
    chunks.push('');

    for (const object of objects) {
      chunks.push(`-- ${object.name} (${object.engine})`);
      chunks.push(await getCreateTable(ch, object.name));
      chunks.push('');

      if (!String(object.name).endsWith('_mv') && !String(object.name).endsWith('_queue')) {
        const columns = await getColumns(ch, object.name);
        chunks.push(`-- Columns for ${object.name}`);
        for (const column of columns) {
          chunks.push(`--   ${column.name}: ${column.type} DEFAULT ${column.default_type || ''} ${column.default_expression || ''}`.trimEnd());
        }
        chunks.push('');
      }
    }

    fs.mkdirSync(path.dirname(OUTPUT_PATH), { recursive: true });
    fs.writeFileSync(OUTPUT_PATH, `${chunks.join('\n')}\n`, 'utf8');
    console.log(`Wrote ${OUTPUT_PATH}`);
  } finally {
    await ch.close();
  }
}

main().catch((error) => {
  console.error(error);
  process.exitCode = 1;
});
